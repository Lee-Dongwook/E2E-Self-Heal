"""Run the safety benchmark on several isolated copies of the demo project at once.

Every scenario breaks the shared demo app with its ``change.patch``, runs the repair graph,
and restores the app, so on one checkout scenarios must run one after another. The wall
clock is then dominated by Playwright rebuilding the app and by model latency, neither of
which uses the machine fully.

Each worker here gets its own copy of the Playwright project (the current directory, for
example ``examples/``) inside a throwaway git repository, its own preview port, and its own
process. Siblings of the project that it only reads (such as the Playwright reporter under
``integrations/``) are symlinked, never copied, so no patch may target them: a corpus whose
patches reach outside the project is rejected before anything starts. A worker runs exactly
the same executor as a sequential run, so results are comparable run for run.
"""

import multiprocessing
import os
import shutil
import socket
import tempfile
import time
from collections.abc import Callable, Sequence
from concurrent.futures import FIRST_EXCEPTION, Future, ProcessPoolExecutor, wait
from dataclasses import dataclass
from pathlib import Path
from multiprocessing.queues import Queue
from typing import Any

import structlog

from app.config import settings
from app.logging import configure_logging
from app.safety_benchmark import (
    ActualOutcome,
    SafetyBenchmarkReport,
    SafetyScenario,
    SafetyScenarioResult,
    _git,
    _result,
    build_report,
    discover_safety_scenarios,
    ScenarioExecutor,
    execute_prepared_scenario,
)

logger = structlog.get_logger(__name__)

# Build output and per-run artifacts: regenerated by every Playwright run, never copied.
_NOT_COPIED = ("node_modules", "test-results", "playwright-report", "dist", ".shadow_workspace")

ResultCallback = Callable[[SafetyScenarioResult], None]


class ParallelSetupError(RuntimeError):
    """The corpus or the working directory cannot be split across project copies."""


@dataclass(frozen=True)
class WorkerSlot:
    """One isolated copy of the project: where it lives and the port its preview server uses."""

    project_dir: Path
    scenario_root: Path  # relative to ``project_dir``
    port: int
    # The worker's stdout and stderr (structured logs, Playwright output), so concurrent workers
    # do not interleave on the caller's terminal. Kept after the run for diagnosis.
    log_path: Path


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def _patch_targets(patch: Path) -> list[str]:
    """Repository-relative paths a ``git diff`` patch writes to."""
    return [
        line[len("+++ b/") :].strip()
        for line in patch.read_text().splitlines()
        if line.startswith("+++ b/")
    ]


def _check_corpus_fits_a_copy(
    scenarios: Sequence[SafetyScenario], repo_root: Path, project_dir: Path, scenario_root: Path
) -> None:
    """Reject a corpus a project copy cannot hold, before any worker is created."""
    if project_dir == repo_root:
        raise ParallelSetupError(
            "--jobs above 1 copies the Playwright project per worker; run it from the project "
            "directory (for example examples/), not the repository root"
        )
    project_prefix = f"{project_dir.relative_to(repo_root).as_posix()}/"
    for scenario in scenarios:
        if scenario.test_path.parent.parent.resolve() != scenario_root:
            raise ParallelSetupError(f"scenario {scenario.name!r} is outside --scenario-root")
        if not scenario.runnable:
            continue
        outside = [
            t for t in _patch_targets(scenario.diff_path) if not t.startswith(project_prefix)
        ]
        if outside:
            raise ParallelSetupError(
                f"scenario {scenario.name!r} patches {', '.join(outside)}, outside the copied "
                f"project {project_prefix}; run it with --jobs 1"
            )


def _build_worker(base: Path, index: int, repo_root: Path, project_rel: Path) -> Path:
    """Copy the project into its own git repository, symlinking every sibling it may read."""
    root = base / f"worker-{index}"
    current_real, current_copy = repo_root, root
    current_copy.mkdir(parents=True)
    for part in project_rel.parts:
        for entry in current_real.iterdir():
            if entry.name not in (part, ".git"):
                (current_copy / entry.name).symlink_to(entry, target_is_directory=entry.is_dir())
        current_real, current_copy = current_real / part, current_copy / part
    shutil.copytree(current_real, current_copy, ignore=shutil.ignore_patterns(*_NOT_COPIED))
    if (current_real / "node_modules").is_dir():
        (current_copy / "node_modules").symlink_to(
            current_real / "node_modules", target_is_directory=True
        )
    initialized = _git(["init", "-q"], cwd=root)
    if initialized.returncode != 0:
        raise ParallelSetupError(
            f"could not create worker repository: {initialized.stderr.strip()}"
        )
    return current_copy


# Per-process state, set once by ``_init_worker`` in each worker process.
_WORKER_SCENARIOS: dict[str, SafetyScenario] = {}
_WORKER_EXECUTOR: list[ScenarioExecutor] = []


def _init_worker(slots: Queue[WorkerSlot], executor: ScenarioExecutor) -> None:
    _WORKER_EXECUTOR.append(executor)
    slot = slots.get()
    log = os.open(slot.log_path, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o644)
    os.dup2(log, 1)
    os.dup2(log, 2)
    os.close(log)
    # A spawned worker starts with structlog's defaults, which render tracebacks with every
    # frame's local variables and skip redaction, so a provider error could write a credential
    # held in a local into this file. Use the app's configuration: plain tracebacks, redacted.
    configure_logging(settings.log_level)
    os.chdir(slot.project_dir)
    os.environ["E2E_DEMO_PORT"] = str(slot.port)
    _WORKER_SCENARIOS.update(
        {scenario.name: scenario for scenario in discover_safety_scenarios(slot.scenario_root)}
    )


def _run_in_worker(name: str, run: int) -> SafetyScenarioResult:
    result = _WORKER_EXECUTOR[0](_WORKER_SCENARIOS[name])
    return result.model_copy(update={"run": run})


def run_parallel_safety_benchmark(
    scenarios: Sequence[SafetyScenario],
    *,
    jobs: int,
    repeats: int = 1,
    on_result: ResultCallback | None = None,
    log_dir: Path,
    executor: ScenarioExecutor = execute_prepared_scenario,
) -> SafetyBenchmarkReport:
    """Run every runnable scenario (``repeats`` times) across ``jobs`` isolated project copies.

    Must be called from the Playwright project directory. ``executor`` runs inside a worker,
    against that worker's copy, so it must be importable (a module-level function). Each
    worker's output goes to ``log_dir/worker-<n>.log``. A :class:`ScenarioRestoreError` in any
    worker stops the run, exactly as it does sequentially. The copies are deleted on the way
    out, whatever happened.
    """
    if jobs < 2:
        raise ValueError("jobs must be at least 2; run sequentially otherwise")
    if repeats < 1:
        raise ValueError("repeats must be at least 1")
    project_dir = Path.cwd().resolve()
    toplevel = _git(["rev-parse", "--show-toplevel"], cwd=project_dir)
    if toplevel.returncode != 0:
        raise ParallelSetupError(f"not inside a git repository ({toplevel.stderr.strip()})")
    repo_root = Path(toplevel.stdout.strip()).resolve()
    ordered = sorted(scenarios, key=lambda item: item.name)
    if not ordered:
        return build_report([])
    scenario_root = ordered[0].test_path.parent.parent.resolve()
    _check_corpus_fits_a_copy(ordered, repo_root, project_dir, scenario_root)

    results: list[SafetyScenarioResult] = [
        _result(scenario, ActualOutcome.SKIPPED, time.monotonic())
        for scenario in ordered
        if not scenario.runnable
    ]
    tasks = [(s.name, run) for run in range(1, repeats + 1) for s in ordered if s.runnable]
    workers = min(jobs, len(tasks)) or 1
    base = Path(tempfile.mkdtemp(prefix="e2e-healer-safety-"))
    context = multiprocessing.get_context("spawn")
    slots: Queue[WorkerSlot] = context.Queue()
    try:
        project_rel = project_dir.relative_to(repo_root)
        for index in range(workers):
            copy = _build_worker(base, index, repo_root, project_rel)
            slots.put(
                WorkerSlot(
                    copy,
                    scenario_root.relative_to(project_dir),
                    _free_port(),
                    log_dir / f"worker-{index}.log",
                )
            )
        logger.info("safety_parallel_started", workers=workers, runs=len(tasks), base=str(base))
        with ProcessPoolExecutor(
            max_workers=workers,
            mp_context=context,
            initializer=_init_worker,
            initargs=(slots, executor),
        ) as pool:
            pending: set[Future[Any]] = {pool.submit(_run_in_worker, *task) for task in tasks}
            while pending:
                done, pending = wait(pending, return_when=FIRST_EXCEPTION)
                for future in done:
                    error = future.exception()
                    if error is not None:
                        pool.shutdown(cancel_futures=True)
                        raise error
                    result: SafetyScenarioResult = future.result()
                    results.append(result)
                    if on_result is not None:
                        on_result(result)
    finally:
        shutil.rmtree(base, ignore_errors=True)
    results.sort(key=lambda result: (result.name, result.run))
    return build_report(results)
